package com.fiscaladmin.joget.approval;

import java.util.HashMap;
import java.util.Map;

import javax.servlet.http.HttpServletRequest;

import org.joget.apps.app.service.AppUtil;
import org.joget.apps.form.dao.FormDataDao;
import org.joget.apps.form.model.FormPermission;
import org.joget.apps.form.model.FormRow;
import org.joget.apps.form.model.FormRowSet;
import org.joget.apps.userview.lib.GroupPermission;
import org.joget.apps.userview.model.UserviewPermission;
import org.joget.commons.util.LogUtil;
import org.joget.directory.model.User;
import org.joget.workflow.util.WorkflowUtil;

/**
 * An act withheld from the person who asked for the record (1.3.0; METHOD-2026-10-16-01, construct
 * 2; MT-DM's request of 15 October 2026, item 2).
 *
 * <p>A permission on a form element, read by the platform for each viewer (Element.isAuthorize;
 * with {@code permissionReadonlyHidden} "true" an element not authorised is not drawn). The record
 * is the one the address names: {@code keyParam} carries its row id, or the value of
 * {@code keyColumn}; it is read through {@code formDefId} from {@code tableName} (a form reads only
 * the columns it places), and its {@code requesterColumn} names who asked for it.
 * <ul>
 *   <li>{@code show} {@code others}, the default: the element is shown to a person who holds one of
 *       {@code allowedGroupIds} (everyone, where it names none; the platform's own GroupPermission
 *       decides) and is not the record's requester. The act bar of a record's form holds a move
 *       withheld from its requester under it, so that she is not offered the move.</li>
 *   <li>{@code show} {@code requester}: the element is shown to the record's requester alone. The
 *       move's own form holds under it the notice that stands in place of the move's button.</li>
 * </ul>
 * A record that names nobody withholds nothing. The four-eyes rule of the decide path, on the
 * service's own decision record ({@link ApprovalService#decide}, {@link ApprovalInbox#eligible}),
 * is not touched. Its config is generated by the kit's projectors from the model.
 */
public class RequesterWithheld extends UserviewPermission implements FormPermission {

    private static final String CLASS_NAME = RequesterWithheld.class.getName();

    @Override public String getName() { return "Requester Withheld"; }
    @Override public String getVersion() { return "1.3.0"; }
    @Override public String getDescription() {
        return "Decision & Approval - an act withheld from the person who asked for the record.";
    }
    @Override public String getLabel() { return "Requester Withheld"; }
    @Override public String getClassName() { return getClass().getName(); }
    @Override public String getPropertyOptions() { return "[]"; }

    @Override
    public boolean isAuthorize() {
        try {
            User user = getCurrentUser();
            String username = user == null || user.getUsername() == null ? "" : user.getUsername();
            HttpServletRequest req = WorkflowUtil.getHttpServletRequest();
            String key = req == null ? "" : req.getParameter(getPropertyString("keyParam"));
            FormDataDao dao = (FormDataDao) AppUtil.getApplicationContext().getBean("formDataDao");
            String requester = dao == null ? "" : requester(dao, getPropertyString("formDefId"),
                    getPropertyString("tableName"), getPropertyString("keyColumn"), key,
                    getPropertyString("requesterColumn"));
            return authorise(getPropertyString("show"), requester, username, inGroups(user));
        } catch (Exception e) {
            // shown, not hidden: the guard and the service refuse a decision by the requester
            LogUtil.error(CLASS_NAME, e, "requester-withheld: could not read the record - shown");
            return !"requester".equals(getPropertyString("show"));
        }
    }

    /** Whether the viewer holds one of {@code allowedGroupIds}, by the platform's GroupPermission. */
    private boolean inGroups(User user) {
        String groups = getPropertyString("allowedGroupIds");
        if (groups == null || groups.trim().isEmpty()) return true;
        GroupPermission gp = new GroupPermission();
        Map<String, Object> p = new HashMap<String, Object>();
        p.put("allowedGroupIds", groups);
        gp.setProperties(p);
        gp.setCurrentUser(user);
        return gp.isAuthorize();
    }

    /**
     * The rule, kept free of the platform (the test seam): {@code show} {@code requester} shows the
     * element to the record's requester alone; anything else shows it to a person in the groups who
     * is not the requester. Names compare without regard to case.
     */
    static boolean authorise(String show, String requester, String username, boolean inGroups) {
        String who = requester == null ? "" : requester.trim();
        String me = username == null ? "" : username.trim();
        if ("requester".equals(show == null ? "" : show.trim())) {
            return !who.isEmpty() && who.equalsIgnoreCase(me);
        }
        if (!inGroups) return false;
        return who.isEmpty() || !who.equalsIgnoreCase(me);
    }

    /** The record's requester: its {@code requesterColumn}, the record found by row id or key; "" otherwise. */
    static String requester(FormDataDao dao, String formDefId, String tableName, String keyColumn,
                            String key, String requesterColumn) {
        if (key == null || key.trim().isEmpty() || formDefId == null || formDefId.isEmpty()
                || tableName == null || tableName.isEmpty()) return "";
        FormRow row;
        if (keyColumn == null || keyColumn.trim().isEmpty() || "id".equals(keyColumn.trim())) {
            row = dao.load(formDefId, tableName, key.trim());
        } else {
            if (!keyColumn.trim().matches("[A-Za-z0-9_]+")) return "";
            FormRowSet rs = dao.find(formDefId, tableName,
                    "WHERE e.customProperties." + keyColumn.trim() + " = ?1",
                    new Object[]{key.trim()}, null, Boolean.FALSE, 0, 2);
            row = rs == null || rs.size() != 1 ? null : rs.get(0);
        }
        String v = row == null ? null : row.getProperty(requesterColumn);
        return v == null ? "" : v.trim();
    }
}
