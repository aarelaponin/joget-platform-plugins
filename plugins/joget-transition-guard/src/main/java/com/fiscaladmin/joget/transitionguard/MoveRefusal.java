/**
 * A refusal's own words on the page (1.6.0; METHOD-2026-10-16-01, construct 1; MT-DM's request of
 * 15 October 2026, item 1).
 *
 * <p>{@link TransitionGuard} refuses a move after its act is saved, as the form's post-processor,
 * and the platform then shows "Form Submitted": a post-processor is given the saved row's id and no
 * form data to write an error on (FormUtil.executePostFormSubmissionProccessor, wflow-core). This
 * validator stands on the move's hidden field of a trigger form, which the platform runs before it
 * stores the act (FormUtil.executeValidators: an element's own validator, skipped only for a
 * read-only element). Given the guard's own properties, the state the move leaves from
 * ({@code fromState}) and the words the model gives each condition ({@code refusals}, one line
 * {@code <condition>|<words>}, the condition a term of the move's guard exactly as written, or
 * {@code withheld_from}), it judges the move as the guard would:
 * <ul>
 *   <li>the record the act names, read through {@code targetForm}; none, or one not in
 *       {@code fromState}, is left to the root guard, which refuses it in its own words;</li>
 *   <li>the person the move is withheld from ({@code withheld}), then each term of the guard in
 *       order; the first that fails decides. Where the model gives it words, they are said at the
 *       head of the form (the form's own error, form.ftl {@code form-error-message}), with
 *       {@code {attribute}} filled from the record, or, for a term {@code none(...)}, from the
 *       first row of the other record that breaks it; the act is not saved; and the history
 *       entries and alerts the model marks for a refusal ({@code refused}) are written, since the
 *       post-processor will not run.</li>
 *   <li>Where the model gives the failed term no words (1.7.0; METHOD-2026-11-03-13, MT-DM's
 *       hand-off of 22 October 2026, item 1), the move is refused all the same, before the save,
 *       in words drawn from the guard: the move's name ({@code moveName}, else its identifier made
 *       into words) and the failed term, filled from the record ({@link #guardWords}). No refused
 *       move ends on "Form Submitted". Until 1.7.0 the save went on and the guard refused it after
 *       the save, behind the platform's "Form Submitted".</li>
 * </ul>
 * Fail-open, as the other validators of this library are: a validator that cannot judge passes,
 * and the guard behind it still refuses. Its config is generated by the kit's projectors from the
 * model; never hand-authored.
 */
public class MoveRefusal extends FormValidator {

    private static final String CN = MoveRefusal.class.getName();
    static final String WITHHELD = "withheld_from";
    static final Pattern PLACEHOLDER = Pattern.compile("\\{([A-Za-z0-9_]+)\\}");

    /** The guard whose rows a refusal writes (1.9.0: so that its clock and its user can be passed in). */
    private final TransitionGuard guard;

    public MoveRefusal() {
        this(new TransitionGuard());
    }

    MoveRefusal(TransitionGuard guard) {
        this.guard = guard;
    }

    @Override public String getName() { return "Move Refusal"; }
    @Override public String getVersion() { return "1.11.0"; }
    @Override public String getDescription() {
        return "Judges a move before its act is saved and says a refusal in the model's own words.";
    }
    @Override public String getLabel() { return "Move Refusal"; }
    @Override public String getClassName() { return getClass().getName(); }
    @Override public String getPropertyOptions() { return "[]"; }
    @Override public String getElementDecoration() { return ""; }

    @Override
    public boolean validate(Element element, FormData data, String[] values) {
        try {
            FormDataDao dao = (FormDataDao) AppUtil.getApplicationContext().getBean("formDataDao");
            if (dao == null) return true;
            Form root = FormUtil.findRootForm(element);
            String keyField = str(getProperties(), "targetField");
            String key = value(keyField, root, data);
            String reasonField = str(getProperties(), "reasonField");
            String reason = reasonField.isEmpty() ? "" : value(reasonField, root, data);
            String words = refuse(getProperties(), dao, guard.actor(), key, reason);
            if (words == null) return true;
            data.addFormError(FormUtil.getElementParameterName(root != null ? root : element), words);
            return false;
        } catch (Exception e) {                       // noqa: fail open; the guard still refuses
            LogUtil.error(CN, e, "move-refusal: could not judge the move - left to the guard");
            return true;
        }
    }

    /** A field's value on this save: the request's, else the element's. */
    private static String value(String fieldId, Form root, FormData data) {
        if (fieldId.isEmpty()) return "";
        String v = data.getRequestParameter(fieldId);
        if ((v == null || v.trim().isEmpty()) && root != null) {
            Element el = FormUtil.findElement(fieldId, root, data);
            if (el != null) v = FormUtil.getElementPropertyValue(el, data);
        }
        return v == null ? "" : v.trim();
    }

    /**
     * The validator's whole work, with its collaborators passed in (the test seam): the words of
     * the refusal, filled, after the rows marked for a refusal are written; or null where the move
     * is not refused here.
     */
    String refuse(Map properties, FormDataDao dao, String actor, String key, String reason) {
        String entity = str(properties, "entity");
        String tableName = str(properties, "tableName");
        String statusField = str(properties, "statusField").isEmpty() ? "status" : str(properties, "statusField");
        String targetForm = str(properties, "targetForm").isEmpty() ? entity : str(properties, "targetForm");
        String transitions = str(properties, "transitions");
        if (entity.isEmpty() || tableName.isEmpty() || transitions.isEmpty()) return null;
        String action = transitions.split("\\|")[0].split(">", -1)[0].trim();
        String[] hit = TransitionGuard.findTransition(transitions, action);
        if (hit == null) return null;
        FormRow record = TransitionGuard.findTarget(dao, targetForm, tableName,
                str(properties, "targetKeyColumn"), key);
        if (record == null) return null;                      // the root guard's to refuse
        String current = nz(record.getProperty(statusField));
        String from = str(properties, "fromState");
        if (!from.isEmpty() && !from.equals(current)) return null;   // the root guard's too
        Map<String, String> words = refusals(str(properties, "refusals"));
        String said = null;
        String why = null;
        String held = TransitionGuard.withheldAttr(str(properties, "withheld"), action);
        String requester = held.isEmpty() ? "" : nz(record.getProperty(held)).trim();
        if (!requester.isEmpty() && requester.equalsIgnoreCase(actor)) {
            String w = words.get(WITHHELD);
            // 1.7.0: words of the guard's own where the model gives none, never "Form Submitted"
            said = w != null ? fill(w, record)
                    : moveName(properties, action) + " is refused: you are the record's "
                      + words(held) + ", and another person makes this move.";
            why = "'" + actor + "' is the record's " + held + " and may not make this move";
        } else if (!hit[2].isEmpty()) {
            for (String term : TransitionGuard.andTerms(hit[2])) {
                boolean other = term.startsWith("none(");
                String fail = other ? guard.evalNone(term, record, record.getId(), properties, dao)
                                    : guard.evalTerm(term, record);
                if (fail == null) continue;
                // the term the form's root guard already asks, in the model's words: its refusal
                if (term.equals(str(properties, "rootAsks"))) return null;
                String w = words.get(term);
                FormRow source = other ? breaker(term, record, properties, dao) : record;
                // 1.7.0: a term the model gives no words is said in the guard's own words, before
                // the save, never left to the post-processor behind "Form Submitted"
                said = w != null ? fill(w, source == null ? new FormRow() : source)
                        : guardWords(moveName(properties, action), term, fail, record);
                why = fail;
                break;
            }
        }
        if (said == null) return null;
        TransitionGuard.Move m = new TransitionGuard.Move("REJECTED: " + why, false, true,
                current, current, reason == null ? "" : reason, guard.stampNow(), said);
        String notWritten = guard.writeRefusedRows(properties, dao, entity, record, record.getId(),
                action, actor, m);
        LogUtil.info(CN, entity + " " + key + " action=" + action + " by " + actor
                + " refused before the save: " + said + notWritten);
        return said;
    }

    /** The move's name as a person reads it: {@code moveName}, else its identifier made into words. */
    static String moveName(Map properties, String action) {
        String named = str(properties, "moveName");
        if (!named.isEmpty()) return named;
        String w = nz(action).replace('_', ' ').trim();
        return w.isEmpty() ? "This move" : Character.toUpperCase(w.charAt(0)) + w.substring(1);
    }

    /**
     * The words of a refusal for a failed term the model gives no words (1.7.0): the move's name
     * and the failed term, filled from the record - for a term over the record, the value the
     * record holds; for a term {@code none(...)}, the count of the other record's rows that break
     * it, as the guard counted them.
     */
    static String guardWords(String move, String term, String fail, FormRow record) {
        String t = nz(term).trim();
        String[] p = t.split("\\s+", 3);
        if (!t.startsWith("none(") && p.length == 3) {
            String held = record == null ? null : record.getProperty(p[0]);
            String now = held == null || held.trim().isEmpty() ? "empty" : held.trim();
            return move + " is refused: " + words(p[0]) + " must " + opWords(p[1]) + " "
                    + p[2] + ", and it is " + now + ".";
        }
        Matcher n = TransitionGuard.NONE.matcher(t);
        Matcher c = Pattern.compile("\\((\\d+) row\\(s\\) of [^)]+\\)\\s*$").matcher(nz(fail));
        String found = c.find() ? c.group(1) : null;
        if (n.matches()) {
            return move + " is refused: it is made only while there is no " + words(n.group(1))
                    + " where " + n.group(2).replace(" = this", " is this record").replace('_', ' ')
                    + (found == null ? "." : ", and " + found + " " + (found.equals("1") ? "is" : "are")
                       + " found.");
        }
        return move + " is refused: the condition " + t + " does not hold.";
    }

    /** An identifier as words: {@code write_off} as {@code write off}. */
    private static String words(String id) { return nz(id).replace('_', ' ').trim(); }

    private static String opWords(String op) {
        switch (op) {
            case "eq": return "be";
            case "ne": return "not be";
            case "gt": return "be more than";
            case "lt": return "be less than";
            case "ge": return "be at least";
            case "le": return "be at most";
            default:   return op;
        }
    }

    /** The first row of the other record that breaks a term {@code none(...)}, or null. */
    static FormRow breaker(String term, FormRow record, Map properties, FormDataDao dao) {
        Matcher m = TransitionGuard.NONE.matcher(term.trim());
        if (!m.matches()) return null;
        String[] place = TransitionGuard.record(properties, m.group(1));
        if (place == null) return null;
        String self = TransitionGuard.thisValue(properties, record, record.getId());
        List<Object> params = new ArrayList<Object>();
        String cond = TransitionGuard.condition(m.group(2), self, params);
        if (cond == null) return null;
        try {
            FormRowSet rows = dao.find(place[0], place[1], cond, params.toArray(), null, null, 0, 1);
            return rows == null || rows.isEmpty() ? null : rows.get(0);
        } catch (Exception e) {
            LogUtil.error(CN, e, "move-refusal: the row that breaks '" + term + "' could not be read");
            return null;
        }
    }

    /** The words of each condition, one line {@code <condition>|<words>}; a line without both is skipped. */
    static Map<String, String> refusals(String lines) {
        Map<String, String> out = new LinkedHashMap<String, String>();
        if (lines == null) return out;
        for (String line : lines.split("\\r?\\n")) {
            int bar = line.indexOf('|');
            if (bar <= 0) continue;
            String when = line.substring(0, bar).trim();
            String says = line.substring(bar + 1).trim();
            if (!when.isEmpty() && !says.isEmpty()) out.put(when, says);
        }
        return out;
    }

    /** The words with each {@code {attribute}} filled from the row; an attribute it lacks is empty. */
    static String fill(String words, FormRow row) {
        Matcher m = PLACEHOLDER.matcher(words);
        StringBuffer sb = new StringBuffer();
        while (m.find()) {
            String v = row == null ? null : row.getProperty(m.group(1));
            m.appendReplacement(sb, Matcher.quoteReplacement(v == null ? "" : v));
        }
        m.appendTail(sb);
        return sb.toString();
    }

    private static String str(Map p, String k) {
        Object v = p == null ? null : p.get(k);
        return v == null ? "" : v.toString().trim();
    }

    private static String nz(String s) { return s == null ? "" : s; }
}
