/**
 * Generic, config-driven lifecycle transition guard. Wired as a form post-submission
 * processor. On save it reads the chosen move ({@code actionField}); if set, it looks the move
 * up in the {@code transitions} config, drives {@link StatusManager#apply} (validated against the
 * mmEntityTransition seed), stamps any set-now effect fields (e.g. submitted_at), and saves once.
 * An illegal move is recorded, not applied. Entity/table/status/action/transitions are all
 * properties, generated by the kit's projectors from the model.
 *
 * <p><b>Two modes.</b> In the first (the ADR-066 engine surface, which carries every move and is
 * posted to by engines and adapters through the application's data API) the form saved IS the
 * record: the guard loads it by the saved row's id, applies the move, clears the action.
 *
 * <p>In the second, the TARGET mode ({@code targetField} set; METHOD-2026-09-25-04, item 3), the
 * form saved is a TRIGGER FORM: a small form per move a person makes, created as a new row in a
 * table of acts — the one path on which the platform runs a post-processor for a person (delta
 * D-015: never on a CRUD edit). The act names the record it moves ({@code targetField}, matched on
 * the record's {@code targetKeyColumn}, or its row id when that is empty); the guard loads the
 * record through {@code targetForm} from {@code tableName}, applies the move to it, copies the
 * move's inputs onto it ({@code copyFields}), saves it, and writes what came of it on the act.
 *
 * <p><b>Who may make the move</b> ({@code checkRoles}; METHOD-2026-09-25-04, item 5). The move's
 * row in mmEntityTransition names the roles that may make it; the actor's roles are the ids of the
 * directory groups they belong to. A move whose row names roles the actor holds none of is refused
 * and recorded as refused. The kit sets it on the trigger forms, the person's path; the engine
 * surface is gated by the application's API credential instead.
 *
 * <p><b>What a move writes beside itself</b> (METHOD-2026-10-08-07, items 1 to 3). A set-now field
 * marked {@code @date} ({@code closed_on@date}) is written as the day alone, {@code yyyy-MM-dd};
 * an unmarked one as the moment, {@code yyyy-MM-dd HH:mm:ss}. After a move it has APPLIED, the
 * guard writes one row for each line of {@code audit} (the history entry, beside the status
 * event) and of {@code notify} (the alert) that names the move; a refused move writes neither.
 * Writing them is fail-soft, as starting a process is: the move stands, and a row not written is
 * said in the result.
 *
 * <p><b>What a refused move writes</b> (METHOD-2026-10-12-14; the owner's ruling of 11 October
 * 2026 on round 1, card 4). A third kind of line, {@code refused}, holds the history entries and
 * alerts the model marks for a refusal. After a move it has REFUSED (its result begins
 * {@code REJECTED:}), the guard writes one row for each of those lines that names the move; an
 * applied move writes none of them, and a refused move still writes no line of {@code audit} or
 * {@code notify}. On a refused move the record did not change, so {@code from} and {@code to}
 * are both the state it stays in. Fail-soft, as the rows of an applied move are: the refusal
 * stands, and a row not written is said in the result.
 *
 * <p><b>Another record's rows</b> (METHOD-2026-10-08-11, items 4 and 5). A guard is one or more
 * terms joined by {@code and}; besides a term over the record moved, a term
 * {@code none(<entity> where <condition>)} counts the rows of another record, read through the
 * form and table its line of {@code records} gives ({@code entity>form>table}), and holds when
 * there are none; a term that cannot be counted refuses the move. In a condition, {@code this}
 * is the record moved as the other record refers to it: its {@code thisKey} attribute, or its row
 * id where {@code thisKey} is empty. A line of {@code related}
 * ({@code action>entity>condition>column=source,...}) sets columns on the rows of a related record
 * that meet the condition, after a move it has applied, in the same run as the move's own save;
 * a source is {@code moment}, {@code today} or a fixed {@code 'word'}. Fail-soft, as the rows
 * written beside a move are. An expression with no {@code none(...)} term is read as before.
 *
 * transitions format: {@code action>toState>nowField1,dayField@date>guardExpr>processId | ...}
 * <br>audit format, one line each: {@code action>form>table>column=source,column='word',...}
 * <br>notify format, one line each: {@code action>role:<id>|attr:<id>>template>form>table>columns}
 * <br>refused format, one line each: {@code audit>} followed by an audit line, or {@code notify>}
 * followed by a notify line
 * <br>records format, one line each: {@code entity>form>table}
 * <br>related format, one line each: {@code action>entity>condition>column=moment|today|'word',...}
 * <br>a source is {@code record}, {@code attr:<attribute of the record moved>}, {@code moment},
 * {@code today}, {@code actor}, {@code from}, {@code to}, {@code move}, {@code reason},
 * {@code entity}, and for an alert {@code recipient} and {@code template}.
 */
public class TransitionGuard extends DefaultApplicationPlugin {

    private static final String CN = TransitionGuard.class.getName();

    /**
     * This bundle's own event carrier. Named here, not set process-wide from the
     * Activator: joget-event-chain is a shared library bundle, and a static default
     * set at bundle start re-aims every other consumer in the same JVM.
     */
    static final String EVENT_FORM = "statusEvent";
    static final String RESULT_FIELD = "transition_result";
    private static final DateTimeFormatter TS = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
    /** The mark of a set-now field written as the day alone (METHOD-2026-10-08-07, item 1). */
    static final String DAY_MARK = "@date";

    public String getName() { return "Lifecycle Transition Guard"; }
    public String getVersion() { return "1.5.0"; }
    public String getDescription() { return "Drives StatusManager transitions from a form action (generated from the L1 model)."; }
    public String getLabel() { return "Lifecycle Transition Guard"; }
    public String getClassName() { return getClass().getName(); }
    public String getPropertyOptions() {
        return AppUtil.readPluginResource(getClassName(), "/properties/transitionGuard.json", null, true, null);
    }

    public Object execute(Map properties) {
        FormDataDao dao = (FormDataDao) AppUtil.getApplicationContext().getBean("formDataDao");
        if (dao == null) { LogUtil.warn(CN, "formDataDao unavailable"); return null; }
        String actor = WorkflowUtil.getCurrentUsername();
        if (actor == null || actor.isEmpty()) actor = "system";
        MmConfigService cfg = new MmConfigService(dao);
        run(properties, dao, cfg, new StatusManager(dao, EVENT_FORM), GroupLookup.DIRECTORY, actor);
        return null;
    }

    /**
     * The guard's whole work, with its collaborators passed in (the test seam). Returns the
     * result written, or null when there was nothing to do.
     */
    String run(Map properties, FormDataDao dao, MmConfigService cfg, StatusManager sm,
               GroupLookup groups, String actor) {
        String entity = str(properties, "entity");
        String tableName = str(properties, "tableName");
        String statusField = def(str(properties, "statusField"), "status");
        String actionField = def(str(properties, "actionField"), "_action");
        String recordId = str(properties, "recordId");
        if (entity.isEmpty() || tableName.isEmpty() || recordId.isEmpty() || recordId.startsWith("#")) return null;

        String targetField = str(properties, "targetField");
        if (targetField.isEmpty()) {
            // ---- the record's own form (the engine surface): the saved row is the record
            FormRow row = dao.load(entity, tableName, recordId);
            if (row == null) return null;
            String action = nz(row.getProperty(actionField));
            if (action.isEmpty()) return null;
            Move m = move(properties, dao, cfg, sm, groups, actor, entity, row, recordId,
                          statusField, action, null);
            if (m == null) return null;
            row.setProperty(actionField, "");
            row.setProperty(RESULT_FIELD, m.result);
            FormRowSet set = new FormRowSet();
            set.add(row);
            dao.saveOrUpdate(entity, tableName, set);
            String result = m.result;
            if (m.applied || m.refused) {
                String said = m.applied
                        ? writeRelated(properties, dao, entity, row, recordId, action, m)
                          + writeRows(properties, dao, entity, row, recordId, action, actor, m)
                        : writeRefusedRows(properties, dao, entity, row, recordId, action, actor, m);
                if (!said.isEmpty()) {
                    result = result + said;
                    row.setProperty(RESULT_FIELD, result);
                    dao.saveOrUpdate(entity, tableName, set);
                }
            }
            LogUtil.info(CN, entity + " " + recordId + " action=" + action + " -> " + result);
            return result;
        }

        // ---- a trigger form: the saved row is the ACT; the record it names is moved
        String actForm = def(str(properties, "actForm"), entity);
        String actTable = str(properties, "actTable");
        if (actTable.isEmpty()) return null;
        FormRow act = dao.load(actForm, actTable, recordId);
        if (act == null) return null;
        String action = nz(act.getProperty(actionField));
        if (action.isEmpty()) return null;
        String key = nz(act.getProperty(targetField)).trim();
        String targetForm = def(str(properties, "targetForm"), entity);
        String keyColumn = str(properties, "targetKeyColumn");
        String result;
        FormRow target = findTarget(dao, targetForm, tableName, keyColumn, key);
        if (target == null) {
            result = "REJECTED: no " + entity + " record " + (key.isEmpty() ? "is named" : "'" + key + "'")
                    + " — the move is made from its record";
        } else {
            Move m = move(properties, dao, cfg, sm, groups, actor, entity, target, target.getId(),
                          statusField, action, act);
            if (m == null) return null;
            result = m.result;
            if (m.applied) {
                FormRowSet set = new FormRowSet();
                set.add(target);
                dao.saveOrUpdate(targetForm, tableName, set);
                result = result
                        + writeRelated(properties, dao, entity, target, target.getId(), action, m)
                        + writeRows(properties, dao, entity, target, target.getId(), action, actor, m);
            } else if (m.refused) {
                result = result
                        + writeRefusedRows(properties, dao, entity, target, target.getId(), action, actor, m);
            }
        }
        act.setProperty(RESULT_FIELD, result);
        FormRowSet aset = new FormRowSet();
        aset.add(act);
        dao.saveOrUpdate(actForm, actTable, aset);
        LogUtil.info(CN, entity + " " + key + " action=" + action + " by " + actor + " -> " + result);
        return result;
    }

    /**
     * What came of a move: its words, whether the record changed, and what the rows written
     * beside it read — the states it left and reached, its reason and its moment.
     */
    static final class Move {
        final String result;
        final boolean applied;
        /** The move was refused: its role or its guard did not allow it (a result REJECTED:). */
        final boolean refused;
        final String from;
        final String to;
        final String reason;
        final LocalDateTime at;
        Move(String result, boolean applied, boolean refused, String from, String to, String reason,
             LocalDateTime at) {
            this.result = result; this.applied = applied; this.refused = refused; this.from = from;
            this.to = to; this.reason = reason; this.at = at;
        }
    }

    /**
     * The history entries and alerts of a refused move (METHOD-2026-10-12-14; the ruling of
     * 11 October 2026 on round 1, card 4): one row for each line of {@code refused} naming the
     * move, a line being {@code audit>} and an audit line, or {@code notify>} and a notify line.
     * Fail-soft, as {@link #writeRows} is: returns what was not written, or "".
     */
    String writeRefusedRows(Map properties, FormDataDao dao, String entity, FormRow record,
                            String recordId, String action, String actor, Move m) {
        StringBuilder said = new StringBuilder();
        for (String line : str(properties, "refused").split("\n")) {
            String l = line.trim();
            int cut = l.indexOf('>');
            if (cut <= 0) continue;
            String kind = l.substring(0, cut).trim();
            String rest = l.substring(cut + 1);
            if ("audit".equals(kind)) {
                said.append(writeAudit(rest, dao, entity, record, recordId, action, actor, m));
            } else if ("notify".equals(kind)) {
                said.append(writeNotify(rest, dao, entity, record, recordId, action, actor, m));
            } else {
                LogUtil.warn(CN, "refused line of an unknown kind '" + kind + "' — not written");
            }
        }
        return said.toString();
    }

    /**
     * The history entries and alerts of an applied move (METHOD-2026-10-08-07, items 2 and 3):
     * one row for each line of {@code audit} and of {@code notify} naming the move, written to the
     * form and table the line names. Fail-soft: returns what was not written, as words to add to
     * the result, or "" when every row was written.
     */
    String writeRows(Map properties, FormDataDao dao, String entity, FormRow record,
                     String recordId, String action, String actor, Move m) {
        StringBuilder said = new StringBuilder();
        for (String line : str(properties, "audit").split("\n")) {
            said.append(writeAudit(line, dao, entity, record, recordId, action, actor, m));
        }
        for (String line : str(properties, "notify").split("\n")) {
            said.append(writeNotify(line, dao, entity, record, recordId, action, actor, m));
        }
        return said.toString();
    }

    /** One audit line ({@code action>form>table>columns}), written where it names the move. */
    private String writeAudit(String line, FormDataDao dao, String entity, FormRow record,
                              String recordId, String action, String actor, Move m) {
        String[] p = line.trim().split(">", -1);
        if (p.length != 4 || !action.equals(p[0].trim())) return "";
        return writeRow(dao, p[1], p[2], p[3], "", "", entity, record, recordId, action,
                actor, m, "history entry");
    }

    /** One notify line ({@code action>to>template>form>table>columns}), where it names the move. */
    private String writeNotify(String line, FormDataDao dao, String entity, FormRow record,
                               String recordId, String action, String actor, Move m) {
        String[] p = line.trim().split(">", -1);
        if (p.length != 6 || !action.equals(p[0].trim())) return "";
        String to = p[1].trim();
        String recipient = to.startsWith("attr:") ? nz(record.getProperty(to.substring(5))) : to;
        return writeRow(dao, p[3], p[4], p[5], recipient, p[2].trim(), entity, record,
                recordId, action, actor, m, "alert");
    }

    private String writeRow(FormDataDao dao, String form, String table, String columns,
                            String recipient, String template, String entity, FormRow record,
                            String recordId, String action, String actor, Move m, String what) {
        form = form.trim();
        table = table.trim();
        try {
            FormRow r = new FormRow();
            r.setId(UUID.randomUUID().toString());
            for (String c : columns.split(",")) {
                int eq = c.indexOf('=');
                if (eq <= 0) continue;
                String col = c.substring(0, eq).trim();
                String src = c.substring(eq + 1).trim();
                String v;
                if (src.length() >= 2 && src.startsWith("'") && src.endsWith("'")) {
                    v = src.substring(1, src.length() - 1);
                } else if (src.startsWith("attr:")) {
                    v = nz(record.getProperty(src.substring(5)));
                } else {
                    switch (src) {
                        case "record":    v = recordId; break;
                        case "moment":    v = m.at.format(TS); break;
                        case "today":     v = m.at.toLocalDate().toString(); break;
                        case "actor":     v = actor; break;
                        case "from":      v = m.from; break;
                        case "to":        v = m.to; break;
                        case "move":      v = action; break;
                        case "reason":    v = m.reason; break;
                        case "entity":    v = entity; break;
                        case "recipient": v = recipient; break;
                        case "template":  v = template; break;
                        default:
                            LogUtil.warn(CN, what + " column '" + col + "': unknown source '" + src + "' — left empty");
                            v = "";
                    }
                }
                r.setProperty(col, v == null ? "" : v);
            }
            FormRowSet set = new FormRowSet();
            set.add(r);
            dao.saveOrUpdate(form, table, set);
            return "";
        } catch (Exception e) {                       // noqa: the move stands regardless
            LogUtil.error(CN, e, what + " not written to " + table + " for " + entity + " " + recordId);
            return " · " + what + " NOT written: " + e.getMessage();
        }
    }

    /**
     * One move on one loaded record: the actor's role, its guard, the state machine, the
     * set-now stamps, the inputs copied from the act, and the process it starts. Returns null
     * when the configuration names no such move.
     */
    private Move move(Map properties, FormDataDao dao, MmConfigService cfg, StatusManager sm,
                      GroupLookup groups, String actor, String entity, FormRow row, String recordId,
                      String statusField, String action, FormRow act) {
        String[] hit = findTransition(str(properties, "transitions"), action);
        if (hit == null) { LogUtil.warn(CN, "no transition for action '" + action + "'"); return null; }
        String target = hit[0];
        String setNowCsv = hit[1];
        String guardExpr = hit[2];
        String startProc = hit[3];
        String current = nz(row.getProperty(statusField));
        String reasonField = str(properties, "reasonField");
        String reason = act == null || reasonField.isEmpty() ? "" : nz(act.getProperty(reasonField)).trim();

        String result;
        boolean applied = false;
        boolean refused = false;
        LocalDateTime at = LocalDateTime.now();
        try {
            if ("true".equalsIgnoreCase(str(properties, "checkRoles"))) {
                String scope = sm.resolveScope(entity, Collections.<String>emptyList());
                String roles = MoveRoles.rolesFor(cfg.entityTransitions(entity, scope), action, current);
                if (!MoveRoles.allows(roles, groups.groupsOf(actor)))
                    throw new InvalidTransitionException(current, target,
                            "'" + actor + "' holds none of the roles that may make this move (" + roles + ")");
            }
            String guardFail = guardExpr.isEmpty() ? null
                    : evalGuard(guardExpr, row, recordId, properties, dao);
            if (guardFail != null)
                throw new InvalidTransitionException(current, target, guardFail);
            sm.apply(entity, row, statusField, recordId, target,
                    Collections.<String>emptyList(), actor, reason.isEmpty() ? action : action + ": " + reason);
            applied = true;
            if (!setNowCsv.isEmpty()) {
                String now = at.format(TS);
                String today = at.toLocalDate().toString();       // yyyy-MM-dd, a date's storage
                for (String f : setNowCsv.split(",")) {
                    String fn = f.trim();
                    if (fn.endsWith(DAY_MARK)) {
                        fn = fn.substring(0, fn.length() - DAY_MARK.length()).trim();
                        if (!fn.isEmpty()) row.setProperty(fn, today);
                    } else if (!fn.isEmpty()) {
                        row.setProperty(fn, now);
                    }
                }
            }
            if (act != null) {
                for (String f : str(properties, "copyFields").split(",")) {
                    String fn = f.trim();
                    if (!fn.isEmpty()) row.setProperty(fn, nz(act.getProperty(fn)));
                }
            }
            result = "OK: " + nz(row.getProperty(statusField));
            if (!startProc.isEmpty()) {
                String p = startProcess(startProc, recordId, entity);
                result = result + " · " + p;
            }
        } catch (InvalidTransitionException e) {
            result = "REJECTED: " + e.getMessage();
            refused = !applied;
        } catch (Exception e) {
            result = "ERROR: " + e.getMessage();
            LogUtil.error(CN, e, "transition failed for " + entity + " " + recordId);
        }
        return new Move(result, applied, refused, current, nz(row.getProperty(statusField)), reason, at);
    }

    /**
     * The record an act names: by its row id when {@code keyColumn} is empty or {@code id}, else
     * the one row whose {@code keyColumn} holds the key. None, or more than one, is no record.
     */
    static FormRow findTarget(FormDataDao dao, String form, String table, String keyColumn, String key) {
        if (key == null || key.trim().isEmpty()) return null;
        if (keyColumn == null || keyColumn.isEmpty() || "id".equals(keyColumn)) {
            return dao.load(form, table, key.trim());
        }
        if (!keyColumn.matches("[A-Za-z0-9_]+")) {
            LogUtil.warn(CN, "targetKeyColumn '" + keyColumn + "' is not a column name — refusing");
            return null;
        }
        FormRowSet rs = dao.find(form, table, "WHERE e.customProperties." + keyColumn + " = ?1",
                new Object[]{key.trim()}, null, Boolean.FALSE, 0, 2);
        return rs == null || rs.size() != 1 ? null : rs.get(0);
    }

    /** returns [toState, setNowCsv, guardExpr, startProcessId] for the matching action, or null. */
    private String[] findTransition(String cfg, String action) {
        if (cfg == null) return null;
        for (String seg : cfg.split("\\|")) {
            String[] p = seg.split(">", -1);
            if (p.length >= 2 && action.equals(p[0].trim())) {
                return new String[]{p[1].trim(),
                        p.length > 2 ? p[2].trim() : "",
                        p.length > 3 ? p[3].trim() : "",
                        p.length > 4 ? p[4].trim() : ""};
            }
        }
        return null;
    }

    /**
     * Launches the process a transition declares, binding the record so the activity's form
     * opens on it. Returns a short outcome string that lands in transition_result.
     *
     * Deliberately FAIL-SOFT: the status change is already committed and legal, and refusing
     * to record it because the workflow engine was unhappy would leave the record in a state
     * the lifecycle says it is not in. A failure here means the officer has no task — visible
     * as an empty inbox and caught by the ui-journey leg — not a corrupt record.
     */
    private String startProcess(String processDefId, String recordId, String entity) {
        try {
            AppDefinition appDef = AppUtil.getCurrentAppDefinition();
            if (appDef == null) return "process " + processDefId + " NOT started: no app context";
            WorkflowManager wm = (WorkflowManager)
                    AppUtil.getApplicationContext().getBean("workflowManager");
            if (wm == null) return "process " + processDefId + " NOT started: no workflowManager";
            // packageId:latest:processDefId — 'latest' so a redeployed package version does not
            // strand the caller on an id that no longer resolves.
            String full = appDef.getId() + ":latest:" + processDefId;
            Map<String, String> vars = new HashMap<String, String>();
            vars.put("recordId", recordId);
            vars.put("id", recordId);
            vars.put("entity", entity);
            WorkflowProcessResult r = wm.processStart(full, null, vars, null, recordId, false);
            if (r == null || r.getProcess() == null)
                return "process " + processDefId + " NOT started (engine returned nothing)";
            LogUtil.info(CN, "started " + full + " for " + entity + " " + recordId
                    + " -> instance " + r.getProcess().getInstanceId());
            return "started " + processDefId;
        } catch (Exception e) {                       // noqa: the status move stands regardless
            LogUtil.error(CN, e, "process start failed for " + processDefId + " / " + recordId);
            return "process " + processDefId + " NOT started: " + e.getMessage();
        }
    }

    /**
     * Evaluates a guard predicate of the form {@code <attr> <op> <literal>} against the loaded
     * row, where op is one of {@code eq ne gt lt ge le} (word operators — '>' and '|' are
     * config separators). Numeric comparison when both sides parse as numbers (empty attr
     * value counts as 0); string comparison otherwise (eq/ne only). Returns null when the
     * guard passes, or a human-readable failure message when it blocks the transition.
     * A malformed expression blocks (fail-closed) — a guard that cannot be evaluated must
     * never silently allow the move.
     */
    private String evalTerm(String expr, FormRow row) {
        String[] p = expr.trim().split("\\s+", 3);
        if (p.length != 3) return "guard unparseable: '" + expr + "'";
        String attr = p[0], op = p[1], lit = p[2];
        String raw = nz(row.getProperty(attr)).trim();
        Double a = num(raw.isEmpty() ? "0" : raw), b = num(lit);
        boolean pass;
        if (a != null && b != null) {
            int c = Double.compare(a, b);
            switch (op) {
                case "eq": pass = c == 0; break;
                case "ne": pass = c != 0; break;
                case "gt": pass = c > 0;  break;
                case "lt": pass = c < 0;  break;
                case "ge": pass = c >= 0; break;
                case "le": pass = c <= 0; break;
                default: return "guard unknown operator: '" + op + "'";
            }
        } else {
            switch (op) {
                case "eq": pass = raw.equals(lit);  break;
                case "ne": pass = !raw.equals(lit); break;
                default: return "guard operator '" + op + "' needs numeric operands ('"
                        + raw + "' " + op + " '" + lit + "')";
            }
        }
        return pass ? null : "guard failed: " + expr + " (actual " + attr + "="
                + (raw.isEmpty() ? "<empty>" : raw) + ")";
    }

    // ------------------------------------------ another record's rows (METHOD-2026-10-08-11)

    static final Pattern NONE = Pattern.compile("^none\\((\\S+) where (.+)\\)$");
    static final String WORD = "[A-Za-z0-9_.\\-]+";
    static final Pattern CMP = Pattern.compile("^([A-Za-z0-9_]+) (?:(=|!=) (" + WORD + ")"
            + "|(in|not in) \\(([^()]*)\\)|(is null|is not null))$");

    /**
     * A move's guard: one or more terms joined by {@code and}. An expression with no
     * {@code none(...)} term is one term over the record, read exactly as before; otherwise each
     * term is asked in turn, and the first that fails refuses the move.
     */
    String evalGuard(String expr, FormRow row, String recordId, Map properties, FormDataDao dao) {
        List<String> terms = andTerms(expr);
        boolean counts = false;
        for (String t : terms) counts |= t.startsWith("none(");
        if (!counts) return evalTerm(expr, row);
        for (String t : terms) {
            String fail = t.startsWith("none(") ? evalNone(t, row, recordId, properties, dao)
                                                : evalTerm(t, row);
            if (fail != null) return fail;
        }
        return null;
    }

    /** {@code none(<entity> where <condition>)}: null when no row meets it; fail-closed. */
    private String evalNone(String term, FormRow row, String recordId, Map properties,
                            FormDataDao dao) {
        Matcher m = NONE.matcher(term.trim());
        if (!m.matches()) return "guard unparseable: '" + term + "'";
        String other = m.group(1);
        String[] place = record(properties, other);
        if (place == null)
            return "guard '" + term + "': the guard is not told where '" + other + "' is kept (records)";
        String self = thisValue(properties, row, recordId);
        if (self.isEmpty())
            return "guard '" + term + "': the record has no " + str(properties, "thisKey") + " to compare";
        List<Object> params = new ArrayList<Object>();
        String cond = condition(m.group(2), self, params);
        if (cond == null) return "guard unparseable: '" + term + "'";
        Long n;
        try {
            n = dao.count(place[0], place[1], cond, params.toArray());
        } catch (Exception e) {       // REFUSE, not pass: a guard that cannot be asked has not held
            LogUtil.error(CN, e, "guard count failed on '" + place[1] + "' — refusing");
            return "guard '" + term + "' could not be counted: " + e.getMessage();
        }
        if (n == null) return "guard '" + term + "' could not be counted";
        return n == 0L ? null : "guard failed: " + term + " (" + n + " row(s) of " + other + ")";
    }

    /**
     * The lines of {@code related} naming the move: the rows of the related record that meet the
     * condition, with the columns set, saved once for each line. Fail-soft: returns what was not
     * written, as words to add to the result, or "" when every line was written.
     */
    String writeRelated(Map properties, FormDataDao dao, String entity, FormRow record,
                        String recordId, String action, Move m) {
        StringBuilder said = new StringBuilder();
        for (String line : str(properties, "related").split("\n")) {
            String[] p = line.trim().split(">", -1);
            if (p.length != 4 || !action.equals(p[0].trim())) continue;
            String other = p[1].trim();
            try {
                String[] place = record(properties, other);
                if (place == null)
                    throw new IllegalStateException("the guard is not told where it is kept (records)");
                String self = thisValue(properties, record, recordId);
                if (self.isEmpty())
                    throw new IllegalStateException("the record has no " + str(properties, "thisKey"));
                List<Object> params = new ArrayList<Object>();
                String cond = condition(p[2].trim(), self, params);
                if (cond == null) throw new IllegalStateException("unparseable: '" + p[2] + "'");
                FormRowSet rows = dao.find(place[0], place[1], cond, params.toArray(),
                        null, null, null, null);
                if (rows == null || rows.isEmpty()) continue;
                for (FormRow r : rows) {
                    for (String c : p[3].split(",")) {
                        int eq = c.indexOf('=');
                        if (eq <= 0) continue;
                        String col = c.substring(0, eq).trim();
                        String src = c.substring(eq + 1).trim();
                        String v;
                        if (src.length() >= 2 && src.startsWith("'") && src.endsWith("'")) {
                            v = src.substring(1, src.length() - 1);
                        } else if ("moment".equals(src)) {
                            v = m.at.format(TS);
                        } else if ("today".equals(src)) {
                            v = m.at.toLocalDate().toString();
                        } else {
                            LogUtil.warn(CN, other + " column '" + col + "': unknown source '" + src + "' — left as it is");
                            continue;
                        }
                        r.setProperty(col, v);
                    }
                }
                dao.saveOrUpdate(place[0], place[1], rows);
            } catch (Exception e) {                   // noqa: the move stands regardless
                LogUtil.error(CN, e, other + " not written for " + entity + " " + recordId);
                said.append(" · ").append(other).append(" NOT written: ").append(e.getMessage());
            }
        }
        return said.toString();
    }

    /** [form, table] of another record, from its line of {@code records}, or null. */
    static String[] record(Map properties, String entity) {
        for (String line : str(properties, "records").split("\n")) {
            String[] p = line.trim().split(">", -1);
            if (p.length == 3 && entity.equals(p[0].trim())
                    && !p[1].trim().isEmpty() && p[2].trim().matches("[A-Za-z0-9_]+"))
                return new String[]{p[1].trim(), p[2].trim()};
        }
        return null;
    }

    /** What {@code this} stands for: the record's {@code thisKey} attribute, or its row id. */
    static String thisValue(Map properties, FormRow row, String recordId) {
        String k = str(properties, "thisKey");
        return k.isEmpty() ? nz(recordId) : nz(row.getProperty(k)).trim();
    }

    /**
     * A condition as the HQL a count or a find over another record's table reads, with its
     * values appended to {@code params} (positional, ?1 ...), or null where it cannot be read.
     */
    static String condition(String cond, String self, List<Object> params) {
        StringBuilder sb = new StringBuilder("WHERE ");
        boolean first = true;
        for (String part : andTerms(cond)) {
            Matcher m = CMP.matcher(part);
            if (!m.matches()) return null;
            String col = "e.customProperties." + m.group(1);
            String c;
            if (m.group(2) != null) {
                params.add("this".equals(m.group(3)) ? self : m.group(3));
                int i = params.size();
                c = "=".equals(m.group(2)) ? col + " = ?" + i
                        : "(" + col + " <> ?" + i + " OR " + col + " IS NULL)";
            } else if (m.group(4) != null) {
                StringBuilder q = new StringBuilder();
                for (String w : m.group(5).split(",")) {
                    w = w.trim();
                    if (!w.matches(WORD)) return null;
                    params.add(w);
                    q.append(q.length() == 0 ? "" : ", ").append("?").append(params.size());
                }
                c = "in".equals(m.group(4)) ? col + " IN (" + q + ")"
                        : "(" + col + " NOT IN (" + q + ") OR " + col + " IS NULL)";
            } else {
                c = "is null".equals(m.group(6)) ? "(" + col + " IS NULL OR " + col + " = '')"
                        : "(" + col + " IS NOT NULL AND " + col + " <> '')";
            }
            sb.append(first ? "" : " AND ").append(c);
            first = false;
        }
        return first ? null : sb.toString();
    }

    /** The terms of an expression joined by {@code and}, split outside parentheses only. */
    static List<String> andTerms(String expr) {
        List<String> out = new ArrayList<String>();
        String s = expr == null ? "" : expr;
        int depth = 0, start = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '(') depth++;
            else if (c == ')') depth--;
            else if (depth == 0 && s.startsWith(" and ", i)) {
                String t = s.substring(start, i).trim();
                if (!t.isEmpty()) out.add(t);
                start = i + 5;
                i += 4;
            }
        }
        String t = s.substring(start).trim();
        if (!t.isEmpty()) out.add(t);
        return out;
    }

    private static Double num(String s) {
        try { return Double.valueOf(s); } catch (NumberFormatException e) { return null; }
    }

    private static String str(Map p, String k) { Object v = p.get(k); return v == null ? "" : v.toString(); }
    private static String def(String v, String d) { return v == null || v.isEmpty() ? d : v; }
    private static String nz(String s) { return s == null ? "" : s; }
}
